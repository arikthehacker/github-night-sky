"""Builds stars.css: the sky gradient plus four tiled SVG star layers.

Run:  python3 make_stars.py
"""
import random
from pathlib import Path
from urllib.parse import quote

GOLD = "#ffe2a0"
LAVENDER = "#e1dcff"


def tile(size, count, colors, seed, glow_chance):
    rnd = random.Random(seed)
    svg = [
        f"<svg xmlns='http://www.w3.org/2000/svg' width='{size}' height='{size}'>",
        "<defs><radialGradient id='g'><stop offset='0' stop-color='currentColor'/>"
        "<stop offset='1' stop-color='currentColor' stop-opacity='0'/></radialGradient></defs>",
    ]
    for _ in range(count):
        x, y, c = rnd.randrange(size), rnd.randrange(size), rnd.choice(colors)
        if rnd.random() < glow_chance:
            svg.append(f"<g color='{c}'><circle cx='{x}' cy='{y}' r='4' fill='url(#g)' opacity='.6'/>"
                       f"<circle cx='{x}' cy='{y}' r='1.3' fill='{c}'/></g>")
        else:
            svg.append(f"<circle cx='{x}' cy='{y}' r='{rnd.choice((0.6, 0.8, 1))}' fill='{c}'/>")
    svg.append("</svg>")
    encoded = quote("".join(svg), safe=" =:/'")
    return f'url("data:image/svg+xml,{encoded}") 0 0 / {size}px'


# (selector, tile, twinkle duration, delay); different tile sizes keep the repeat from lining up
layers = [
    ("html::before", tile(557, 34, [GOLD, LAVENDER, LAVENDER], 1, 0), None, None),
    ("html::after", tile(683, 16, [GOLD], 2, 0.2), "5.3s", "0s"),
    ("body::before", tile(743, 16, [GOLD], 3, 0.15), "7.1s", "-3s"),
    ("body::after", tile(811, 18, [LAVENDER], 4, 0.1), "6.2s", "-1.4s"),
]

sky = """radial-gradient(ellipse 45% 40% at 82% 8%, #966e8c59, transparent 70%),
    radial-gradient(ellipse 40% 35% at 12% 88%, #8c5a5a38, transparent 70%),
    radial-gradient(ellipse 60% 50% at 50% 45%, #46408240, transparent 75%),
    linear-gradient(#2c2856, #26224a 45%, #1c1937)"""

css = [
    "/* generated by make_stars.py, do not edit by hand */",
    "html::before, html::after, body::before, body::after {",
    '  content: ""; position: fixed; inset: 0; z-index: -1; pointer-events: none;',
    "}",
]
for selector, stars, duration, delay in layers:
    if duration is None:
        css.append(f"{selector} {{\n  background: {stars},\n    {sky};\n}}")
    else:
        css.append(f"{selector} {{\n  background: {stars};\n"
                   f"  animation: gh-night-twinkle {duration} ease-in-out {delay} infinite alternate;\n"
                   "  will-change: opacity;\n}")
css += [
    "@keyframes gh-night-twinkle { from { opacity: .25; } to { opacity: 1; } }",
    "@media (prefers-reduced-motion: reduce) {",
    "  html::after, body::before, body::after { animation: none; opacity: .7; }",
    "}",
]

out = Path(__file__).resolve().parent / "stars.css"
out.write_text("\n".join(css) + "\n")
print(f"wrote {out} ({out.stat().st_size} bytes)")
